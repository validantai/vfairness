"""A published page may not offer a link that cannot resolve.

THE DEFECT THIS EXISTS FOR. The site-wide footer carried
``https://validant.ai/contact`` on all 18 pages that have a footer.
``https://validant.ai/contact`` returns 404, and had done since at least
2026-08-22, when the project's own docs-validation register recorded it as "the
only live call to action in the entire Support section ... is a dead link". Six
days later it was still on every page. That is not a link that rotted quietly in
a corner: it was the one way a reader was offered to get in touch.

A second family had the same shape and a worse cause. Twelve prominent
call-to-action blocks linked to
``github.com/validantai/vfairness/blob/main/notebooks/<name>.ipynb``. Those can
never resolve in the public repository, because ``notebooks`` is on the export
script's EXCLUDES list: the saved ``.ipynb`` outputs embed local development
paths, so the directory is deliberately never published. The links were not
stale, they were structurally impossible, and no check could see that because
each one is a perfectly well-formed URL.

WHAT THIS FILE CHECKS, and why in this shape.

1. **A registry of URLs verified dead**, with the date and the command. This is
   offline and deterministic: a network link-checker in a unit test is a test
   that fails on a train. The registry is a fact recorded once and enforced
   forever, which is what the 2026-08-22 finding needed and did not get.
2. **Repository paths the publish boundary deletes.** Derived from a recorded
   list rather than from the export script, which lives in the private monorepo
   and is not part of this repository at all.
3. **Every relative link resolves**, file and ``#fragment`` alike, which is a
   whole class the two registries above cannot reach.

An opt-in live check is included for the case a maintainer wants it, and it is
SKIPPED unless ``VFAIRNESS_CHECK_EXTERNAL_LINKS=1``. It is stated here plainly
rather than left to look like coverage: **it does not run in CI**, so nothing in
this repository re-verifies the registry automatically. What the registry is, is
a fact that was checked by hand on a stated date and is enforced from then on.
"""

from __future__ import annotations

import os
import re
from html import unescape
from pathlib import Path
from typing import Dict, List, Set, Tuple
from urllib.parse import unquote, urlparse

import pytest

LIB_ROOT = Path(__file__).resolve().parents[1]
SITE = LIB_ROOT / "docs" / "site"

_HREF_RE = re.compile(r'href="([^"]+)"')
_ID_RE = re.compile(r'\bid="([^"]+)"')
_NAME_RE = re.compile(r'\bname="([^"]+)"')


# --------------------------------------------------------------------------
# 1. URLs verified dead. Add to this only after checking, and say when.
# --------------------------------------------------------------------------

DEAD_URLS: Dict[str, str] = {
    "https://validant.ai/contact": (
        "404 on 2026-08-22 (docs/audits/docs-validation-findings-2026-08-22.md) and again on "
        "2026-08-28. Verified not to be bot-blocking or a SPA artifact: /imprint and /privacy "
        "answer 200 to the identical request, and /contact returns the same generic shell as a "
        "path that was never published. The footer 'Contact' entry points at "
        "https://validant.ai/imprint#publisher instead, which is where the site publishes its "
        "own contact addresses."
    ),
}

# Paths inside the public repository that the publish boundary deletes, so a
# link into them is a promise the published repository cannot keep. Recorded
# here rather than read from the export script, which is not part of this
# repository.
UNPUBLISHED_REPO_PATHS: Dict[str, str] = {
    # "notebooks" WAS here, and this is the entry coming OFF the list rather than
    # onto it. The export dropped the directory because saved .ipynb outputs
    # embedded local development paths, so twelve call-to-action blocks had to be
    # downgraded from links to plain notes. On 2026-09-07 the six offending paths
    # (in two of thirteen notebooks, all inside captured warning output) were
    # replaced with placeholders and the directory was published, so those twelve
    # are real links again. `notebooks/output` stays unpublished, below.
    "notebooks/output": (
        "47 files, 5.6 MB, every one of them regenerated by running the notebook that "
        "produced it. The notebooks themselves ARE published; their saved artifacts are "
        "not, so a link into this directory cannot resolve for a reader."
    ),
    "docs/audits": (
        "audit records are internal and are dropped by the export, so a link into them from a "
        "published page cannot resolve for a reader."
    ),
    "spikes": "dropped by the export as internal work.",
}

# Repository paths a page may name in prose. Restricted to two trees that exist
# in the published repository as well as this one.
_REPO_PATH_RE = re.compile(r"(?:tests|src/vfairness)/[A-Za-z0-9_./-]+\.(?:py|svg|json)")

# A cited pytest node id: `tests/test_x.py::TestY::test_z`.
_NODE_ID_RE = re.compile(r"tests/[A-Za-z0-9_/]+\.py::[A-Za-z0-9_:]+")

_REPO_BLOB_RE = re.compile(
    r"https://github\.com/validantai/vfairness/(?:blob|tree|raw)/[^/]+/([^\s\"#?]+)"
)


def site_pages() -> Dict[Path, str]:
    pages = {path: path.read_text(encoding="utf-8") for path in sorted(SITE.rglob("*.html"))}
    assert pages, f"no HTML under {SITE}; every check in this file would pass by finding nothing"
    return pages


def hrefs(html: str) -> List[str]:
    return _HREF_RE.findall(html)


def dead_link_problems(pages: Dict[Path, str], registry: Dict[str, str] = DEAD_URLS) -> List[str]:
    problems: List[str] = []
    for path, html in sorted(pages.items()):
        for href in hrefs(html):
            for dead, why in registry.items():
                if href == dead or href.startswith(dead + "?") or href.startswith(dead + "#"):
                    rel = (
                        path.relative_to(SITE)
                        if SITE in path.parents or path.parent == SITE
                        else path
                    )
                    problems.append(f"{rel}: links to {href}, recorded dead. {why}")
    return problems


def unpublished_path_problems(
    pages: Dict[Path, str], registry: Dict[str, str] = UNPUBLISHED_REPO_PATHS
) -> List[str]:
    problems: List[str] = []
    for path, html in sorted(pages.items()):
        for match in _REPO_BLOB_RE.finditer(html):
            target = match.group(1)
            for prefix, why in registry.items():
                if target == prefix or target.startswith(prefix + "/"):
                    rel = path.relative_to(SITE) if path.is_relative_to(SITE) else path
                    problems.append(
                        f"{rel}: links to the repository path {target!r}, which is never "
                        f"published: {why}"
                    )
    return problems


# --------------------------------------------------------------------------
# 3. Relative links resolve, target file and #fragment alike.
# --------------------------------------------------------------------------

_IGNORED_SCHEMES = ("http:", "https:", "mailto:", "tel:", "javascript:", "data:")


def _anchors(html: str) -> Set[str]:
    return set(_ID_RE.findall(html)) | set(_NAME_RE.findall(html))


def _resolve(page: Path, target: str) -> "Path | None":
    """Where a href lands on disk, the way the host serves this site.

    A leading ``/`` is site-root-relative, not filesystem-root-relative: getting
    that wrong reports every link in the 404 page as broken. Clean URLs are
    honoured too (``/concepts/changelog`` is ``concepts/changelog.html``), which
    is how the pages are actually written and served.
    """
    base = SITE if target.startswith("/") else page.parent
    candidate = (base / target.lstrip("/")).resolve()
    if candidate.is_dir():
        index = candidate / "index.html"
        return index if index.is_file() else None
    if candidate.is_file():
        return candidate
    with_html = candidate.with_name(candidate.name + ".html")
    if with_html.is_file():
        return with_html
    return None


def relative_link_problems(pages: Dict[Path, str]) -> List[str]:
    """Every non-external href must name a file that exists, and an anchor that exists.

    A fragment on the CURRENT page is checked against that page. A fragment on
    another page is checked against that page's ids, which is what caught a
    hand-written cross-page anchor that pointed at a section id nobody had
    written.
    """
    problems: List[str] = []
    anchor_cache: Dict[Path, Set[str]] = {}

    def anchors_of(path: Path) -> Set[str]:
        if path not in anchor_cache:
            anchor_cache[path] = _anchors(path.read_text(encoding="utf-8"))
        return anchor_cache[path]

    for path, html in sorted(pages.items()):
        rel = path.relative_to(SITE)
        own = _anchors(html)
        for href in hrefs(html):
            if href.startswith(_IGNORED_SCHEMES) or href.startswith("//"):
                continue
            parsed = urlparse(href)
            fragment = unquote(parsed.fragment)
            target_path = unquote(parsed.path)
            if not target_path:
                if fragment and fragment not in own and fragment != "":
                    problems.append(f"{rel}: '#{fragment}' names no id on this page")
                continue
            resolved = _resolve(path, target_path)
            if resolved is None:
                problems.append(
                    f"{rel}: href {href!r} names no file under docs/site (tried the path itself, "
                    "+'.html', and its index.html)"
                )
                continue
            if fragment and resolved.suffix == ".html" and fragment not in anchors_of(resolved):
                problems.append(
                    f"{rel}: href {href!r} names the anchor '#{fragment}', which "
                    f"{resolved.relative_to(SITE)} does not define"
                )
    return problems


