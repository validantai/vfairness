# recoverable is a link whose target the export never ships, or whose path is
# simply wrong. That link 404s on the day the repository is populated and keeps
# 404ing, with nothing to notice it, which is exactly how the twelve notebook
# links recorded at the top of this file happened.
#
# Verified by hand 2026-09-07 against a built export tree: all nine targets ship.
# This turns that one-off check into a standing one.

_MD_LINK_RE = re.compile(r"\]\(\s*(<[^>]+>|[^)\s]+)")


def shipped_markdown() -> Dict[Path, str]:
    """Markdown a reader of the published repository can open.

    docs/audits is excluded deliberately: it is internal, the export drops it
    (see UNPUBLISHED_REPO_PATHS), so a link inside it can never mislead a reader.
    """
    paths = sorted(LIB_ROOT.glob("*.md")) + sorted(LIB_ROOT.glob("docs/*.md"))
    pages = {p: p.read_text(encoding="utf-8") for p in paths}
    assert pages, f"no shipped markdown found under {LIB_ROOT}"
    return pages


def _blob_targets(text: str) -> List[str]:
    """Repository paths named by a blob link, in MARKDOWN.

    _REPO_BLOB_RE was written for HTML, where the URL ends at the closing quote
    of an href. In markdown it is `](url)`, so the match runs on into the closing
    paren and whatever punctuation follows it, and the path is reported as
    'NOTICE).' instead of 'NOTICE'. Trim at the paren, then strip trailing
    sentence punctuation.
    """
    out: List[str] = []
    for m in _REPO_BLOB_RE.finditer(text):
        target = m.group(1).split(")")[0].rstrip(".,;:")
        if target:
            out.append(target)
    return out


def test_every_repository_link_in_shipped_markdown_points_at_a_real_file() -> None:
    """A blob link to a path that does not exist 404s forever, silently."""
    problems: List[str] = []
    for path, text in sorted(shipped_markdown().items()):
        for target in _blob_targets(text):
            if not (LIB_ROOT / target).exists():
                problems.append(
                    f"{path.relative_to(LIB_ROOT)}: links to {target!r}, which does not "
                    f"exist in this repository, so it will 404 in the public one too"
                )
    assert not problems, "\n".join(problems)


def test_no_shipped_markdown_links_into_a_path_the_export_deletes() -> None:
    problems = unpublished_path_problems(shipped_markdown())
    assert not problems, "\n".join(problems)


def _md_urls(text: str) -> List[str]:
    """Absolute URLs a markdown link points at.

    dead_link_problems() cannot be reused here: it extracts `href="..."`, which
    markdown does not contain, so it silently returns nothing. That made the
    first version of this test pass while a link to a URL recorded dead sat in
    README.md, which the sabotage run caught and a review would not have.
    """
    out: List[str] = []
    for m in _MD_LINK_RE.finditer(text):
        url = m.group(1).strip("<>")
        if url.startswith(("http://", "https://")):
            out.append(url.split(" ")[0].rstrip(".,;:"))
    return out


def test_no_shipped_markdown_links_to_a_url_recorded_dead() -> None:
    problems: List[str] = []
    for path, text in sorted(shipped_markdown().items()):
        for url in _md_urls(text):
            for dead, why in DEAD_URLS.items():
                if url == dead or url.startswith(dead + "?") or url.startswith(dead + "#"):
                    problems.append(
                        f"{path.relative_to(LIB_ROOT)}: links to {url}, recorded dead. {why}"
                    )
    assert not problems, "\n".join(problems)


def test_the_markdown_sweep_actually_reads_the_readme_and_finds_links() -> None:
    """NON-VACUITY. Three tests above would pass forever on an empty scan, and
    the README is the specific file they exist to protect."""
    pages = shipped_markdown()
    readme = LIB_ROOT / "README.md"
    assert readme in pages, "README.md is not being scanned"
    blob_links = [t for text in pages.values() for t in _blob_targets(text)]
    assert len(blob_links) >= 5, (
        f"only {len(blob_links)} repository links found across the shipped markdown; "
        "the extractor is broken"
    )
    assert _blob_targets(pages[readme]), "no repository links found in README.md itself"
    urls = [u for text in pages.values() for u in _md_urls(text)]
    assert len(urls) >= 10, (
        f"only {len(urls)} absolute URLs extracted from the shipped markdown; the "
        "dead-link scan above would be checking almost nothing"
    )
