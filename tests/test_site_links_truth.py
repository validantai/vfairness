class TestTheseChecksAreThemselvesChecked:
    """Plant each defect and require it to be reported.

    Everything here is a synthetic page held in memory; no repository file is
    read or written, so these controls keep working whatever the real pages say.
    """

    def _page(self, html: str) -> Dict[Path, str]:
        return {SITE / "probe.html": html}

    def test_the_dead_footer_link_is_caught(self) -> None:
        problems = dead_link_problems(
            self._page('<li><a href="https://validant.ai/contact" target="_blank">Contact</a></li>')
        )
        assert problems, "the exact link that shipped on 18 pages passed the check"
        assert "validant.ai/contact" in problems[0]

    def test_a_query_string_does_not_launder_a_dead_link(self) -> None:
        problems = dead_link_problems(
            self._page('<a href="https://validant.ai/contact?src=docs">c</a>')
        )
        assert problems, problems

    def test_a_live_link_on_the_same_host_is_not_caught(self) -> None:
        assert (
            dead_link_problems(self._page('<a href="https://validant.ai/imprint#publisher">c</a>'))
            == []
        )

    def test_a_link_into_the_notebook_artifact_directory_is_caught(self) -> None:
        """The detector still fires on a genuinely unpublished path.

        This control used to plant a link to a NOTEBOOK, because the whole
        directory was unpublished. The notebooks were published on 2026-09-07, so
        that link is now legitimate and the control had to move to a path that is
        still excluded: their regenerated artifact directory. Retargeting it,
        rather than deleting it, is what keeps the detector proven.
        """
        problems = unpublished_path_problems(
            self._page(
                '<a href="https://github.com/validantai/vfairness/blob/main/notebooks/'
                'output/bias_audit.svg">Artifact</a>'
            )
        )
        assert problems, "a link into the excluded notebooks/output/ directory passed the check"
        assert "notebooks/output" in problems[0]

    def test_a_link_to_a_notebook_itself_is_not_caught(self) -> None:
        """The inverse, which is the half that would have gone unnoticed.

        Twelve documentation call-to-action blocks point at these notebooks. If
        the registry ever re-excludes the directory, or the prefix match widens
        from `notebooks/output` to `notebooks`, every one of them starts failing
        and this says so immediately.
        """
        assert not unpublished_path_problems(
            self._page(
                '<a href="https://github.com/validantai/vfairness/blob/main/notebooks/'
                'vfairness_4_metrics_demo.ipynb">Demo</a>'
            )
        ), "a link to a PUBLISHED notebook was reported as unpublishable"

    def test_a_link_to_a_published_repository_path_is_not_caught(self) -> None:
        assert (
            unpublished_path_problems(
                self._page(
                    '<a href="https://github.com/validantai/vfairness/blob/main/docs/'
                    'DIVERGENCES.md">Divergences</a>'
                )
            )
            == []
        )

    def test_a_prefix_that_only_looks_like_an_excluded_path_is_not_caught(self) -> None:
        # `notebooks_archive` is not `notebooks`; a substring test would refuse it.
        assert (
            unpublished_path_problems(
                self._page(
                    '<a href="https://github.com/validantai/vfairness/blob/main/'
                    'notebooks_archive/x.md">x</a>'
                )
            )
            == []
        )

    def test_the_stale_test_citation_is_caught(self) -> None:
        """The exact string that shipped: a red build reported by a test that was gone."""
        known = {
            "tests/test_docs_truth.py": {"test_changelog_top_section_is_the_unreleased_version"}
        }
        problems = node_id_problems(
            {
                "docs/QUALITY_AND_HARDENING.md": (
                    "One test is failing on `main`. "
                    "`tests/test_docs_truth.py::test_changelog_unreleased_section_is_empty` asserts"
                )
            },
            known,
        )
        assert problems and "defines no" in problems[0], problems

    def test_a_citation_of_a_module_that_is_gone_is_caught(self) -> None:
        problems = node_id_problems(
            {"page.html": "see tests/test_deleted_module.py::test_a"},
            {"tests/test_docs_truth.py": {"test_a"}},
        )
        assert problems and "does not exist" in problems[0], problems

    def test_a_live_citation_is_not_caught(self) -> None:
        assert (
            node_id_problems(
                {"page.html": "see tests/test_docs_truth.py::test_a"},
                {"tests/test_docs_truth.py": {"test_a"}},
            )
            == []
        )

    def test_a_bare_function_name_is_not_treated_as_a_citation(self) -> None:
        # A historical record naming a test that no longer exists writes the bare
        # name for exactly this reason; the rule must leave it alone.
        assert (
            node_id_problems({"page.html": "test_changelog_unreleased_section_is_empty"}, {}) == []
        )

    def test_a_class_scoped_node_id_resolves_by_its_leaf(self) -> None:
        assert (
            node_id_problems(
                {"page.html": "tests/test_x.py::TestThing::test_a"},
                {"tests/test_x.py": {"test_a", "TestThing"}},
            )
            == []
        )

    def test_a_relative_link_to_a_missing_file_is_caught(self) -> None:
        problems = relative_link_problems(self._page('<a href="nowhere/index.html">x</a>'))
        assert problems and "names no file" in problems[0], problems

    def test_a_clean_url_that_does_resolve_is_not_caught(self) -> None:
        # `/concepts/changelog` is served from concepts/changelog.html; a checker
        # that demanded the extension would report every such link as broken and
        # then be deleted for crying wolf.
        assert (
            relative_link_problems({SITE / "probe.html": '<a href="/concepts/changelog">x</a>'})
            == []
        )

    def test_a_root_relative_link_resolves_against_the_site_root(self) -> None:
        assert relative_link_problems({SITE / "legal" / "probe.html": '<a href="/">home</a>'}) == []

    def test_a_fragment_that_names_no_anchor_is_caught(self) -> None:
        problems = relative_link_problems(
            self._page('<h1 id="here">t</h1><a href="#nowhere">x</a>')
        )
        assert problems and "names no id" in problems[0], problems

    def test_a_fragment_that_does_exist_is_not_caught(self) -> None:
        assert relative_link_problems(self._page('<h1 id="here">t</h1><a href="#here">x</a>')) == []

    def test_a_cross_page_fragment_is_checked_against_that_page(self) -> None:
        problems = relative_link_problems(
            {SITE / "probe.html": '<a href="api-reference/index.html#not-a-section">x</a>'}
        )
        assert problems and "does not define" in problems[0], problems


# --------------------------------------------------------------------------
# Opt in, and NOT part of CI. Stated so the registry above is not mistaken for
# a live check.
# --------------------------------------------------------------------------


@pytest.mark.skipif(
    os.environ.get("VFAIRNESS_CHECK_EXTERNAL_LINKS") != "1",
    reason="opt-in network check; set VFAIRNESS_CHECK_EXTERNAL_LINKS=1 to run it",
)
def test_every_external_link_answers(capsys: pytest.CaptureFixture) -> None:
    """Re-verify the registry by hand, in three states rather than two.

    Deliberately not enabled in CI. A network check that runs on every push turns
    an unrelated outage into a red build and gets disabled, at which point it is
    a guard that cannot fail. Run it before a release instead.

    THE THREE STATES MATTER HERE MORE THAN USUAL. The first version of this
    check failed 403 and treated it as dead. Twenty-two of the links on this
    site are ``doi.org`` and publisher URLs that answer 403 to any script, plus
    two font-CDN preconnect ORIGINS that are not pages at all. Reported as
    failures they are noise, and a check that cries wolf gets deleted, which is
    the same end state as a check that cannot fail. So:

    * **dead** (404 / 410 / a host that does not resolve) fails this test;
    * **could not check** (403, 405, 429, a TLS chain this interpreter cannot
      build, a timeout) is PRINTED and does not fail, because it is not evidence
      the page is gone;
    * a floor on the number verified live stops the whole run passing by
      checking nothing.
    """
    import urllib.error
    import urllib.request

    urls: Set[str] = set()
    for html in site_pages().values():
        for href in hrefs(html):
            if not href.startswith("http"):
                continue
            # A bare origin in a <link rel="preconnect"> is not a page.
            if not urlparse(href).path.strip("/"):
                continue
            urls.add(unescape(href))

    dead: List[Tuple[str, str]] = []
    unchecked: List[Tuple[str, str]] = []
    live = 0
    for url in sorted(urls):
        request = urllib.request.Request(
            url, headers={"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"}
        )
        try:
            with urllib.request.urlopen(request, timeout=30) as response:  # noqa: S310
                if response.status in {404, 410}:
                    dead.append((url, str(response.status)))
                elif response.status >= 400:
                    unchecked.append((url, str(response.status)))
                else:
                    live += 1
        except urllib.error.HTTPError as exc:
            (dead if exc.code in {404, 410} else unchecked).append((url, str(exc.code)))
        except Exception as exc:  # noqa: BLE001  - never silently pass
            unchecked.append((url, f"{type(exc).__name__}: {exc}"))

    with capsys.disabled():
        print(f"\nexternal links: {live} live, {len(dead)} dead, {len(unchecked)} could not check")
        for url, why in unchecked:
            print(f"  could not check: {url} -> {why}")
    assert live >= 30, f"only {live} links verified live; this run established almost nothing"
    assert not dead, "\n".join(f"{u} -> {c}" for u, c in dead)


