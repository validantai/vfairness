def test_the_sweep_reads_every_shipped_page_and_finds_links() -> None:
    """Guard against a vacuous run before trusting any result below."""
    pages = site_pages()
    assert len(pages) >= 18, len(pages)
    total = sum(len(hrefs(html)) for html in pages.values())
    assert total > 500, f"only {total} hrefs found across {len(pages)} pages; the parser is broken"


def test_no_published_page_links_to_a_url_recorded_dead() -> None:
    problems = dead_link_problems(site_pages())
    assert not problems, "\n".join(problems)


def test_no_published_page_links_into_a_path_the_export_deletes() -> None:
    problems = unpublished_path_problems(site_pages())
    assert not problems, "\n".join(problems)


def test_every_relative_link_and_anchor_resolves() -> None:
    problems = relative_link_problems(site_pages())
    assert not problems, f"{len(problems)} unresolvable links:\n" + "\n".join(problems)


def test_every_repository_path_named_on_a_page_exists() -> None:
    """A page that points at a file must point at a file that is there.

    ``docs/site/quality-and-hardening/index.html`` reported a failing test by
    name, in a "What Is Still Open" table dated the same day, after the test had
    been replaced. That is the same defect as a dead link, in prose: a pointer
    into the repository that no longer resolves. Restricted to ``tests/`` and
    ``src/vfairness/``, which exist in both the development repository and the
    published one, so this cannot go red on day one in the public repo the way a
    check over ``docs/audits/`` would.
    """
    problems: List[str] = []
    for path, raw in sorted(site_pages().items()):
        text = unescape(raw)
        for named in sorted(set(_REPO_PATH_RE.findall(text))):
            if not (LIB_ROOT / named).exists():
                problems.append(f"{path.relative_to(SITE)}: names {named!r}, which does not exist")
    assert not problems, "\n".join(problems)


def test_every_test_named_as_a_node_id_in_the_docs_exists() -> None:
    """A document that cites a test by node id must cite one that is there.

    ``docs/QUALITY_AND_HARDENING.md`` and its published page reported a red
    build under "What Is Still Open", dated the same day, naming
    ``test_changelog_unreleased_section_is_empty``. That test had been replaced;
    the failure it described was closed and the page still advertised it. The
    inverse of the fabrication class the rest of this project chases, and it
    reads as current state to anybody who lands there.

    The rule is deliberately narrow: it fires only on a FULL ``file.py::name``
    node id, which is a pointer, and not on a bare function name, which is how a
    historical record refers to something that no longer exists.
    """
    sources: Dict[str, str] = {}
    for path in sorted(SITE.rglob("*.html")):
        sources[str(path.relative_to(LIB_ROOT))] = unescape(path.read_text(encoding="utf-8"))
    for path in sorted((LIB_ROOT / "docs").glob("*.md")):
        sources[str(path.relative_to(LIB_ROOT))] = path.read_text(encoding="utf-8")

    problems = node_id_problems(sources, _collected_test_names())
    assert not problems, "\n".join(problems)


def node_id_problems(sources: Dict[str, str], known: Dict[str, Set[str]]) -> List[str]:
    """Cited node ids that name no module, or no test inside the module they name."""
    problems: List[str] = []
    for where, text in sorted(sources.items()):
        for node_id in sorted(set(_NODE_ID_RE.findall(text))):
            module, _, name = node_id.partition("::")
            leaf = name.rsplit("::", 1)[-1]
            if module not in known:
                problems.append(f"{where}: cites {node_id}, but {module} does not exist")
            elif leaf not in known[module]:
                problems.append(f"{where}: cites {node_id}, but {module} defines no {leaf}")
    return problems


def _collected_test_names() -> Dict[str, Set[str]]:
    """Every ``def test_*`` per test module, read from the source.

    Parsed rather than collected through pytest: this runs inside a pytest
    session already, and the question here is only whether a name a document
    points at is present in the file it names.
    """
    found: Dict[str, Set[str]] = {}
    for path in sorted((LIB_ROOT / "tests").rglob("*.py")):
        key = str(path.relative_to(LIB_ROOT))
        found[key] = set(
            re.findall(
                r"^\s*(?:async )?def (test_[A-Za-z0-9_]+)", path.read_text(encoding="utf-8"), re.M
            )
        ) | set(re.findall(r"^class (Test[A-Za-z0-9_]+)", path.read_text(encoding="utf-8"), re.M))
    return found


def test_the_footer_still_offers_a_way_to_make_contact() -> None:
    """The repair must not be "delete the call to action".

    Removing the dead link would satisfy every check above and leave a reader
    with no way to reach anyone, which is a worse page than the broken one.
    """
    pages = site_pages()
    with_footer = [p for p, html in pages.items() if ">Contact</a>" in html]
    assert len(with_footer) >= 18, (
        f"only {len(with_footer)} pages carry a footer Contact entry; it was on 18"
    )
    for path in with_footer:
        html = pages[path]
        match = re.search(r'href="([^"]+)"[^>]*>Contact</a>', html)
        assert match, path
        assert match.group(1) not in DEAD_URLS, path


