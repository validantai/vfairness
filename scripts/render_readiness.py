def _measured(c: dict, unconfirmed: int, examined: int) -> str:
    """A condition's measurement in the reader's units: code units, as in the heat map."""
    if c["id"] == "B4" and not c["passes"]:
        return (
            f"{unconfirmed:,} of {examined:,} examined code units still need a second examiner "
            f"(the gate counts {c['measured']} grades; some are a second name for the same code)"
        )
    if c["id"] == "B1" and not c["passes"]:
        import re

        names = re.findall(r"vfairness\.[\w.]+", str(c["measured"]))
        short = ", ".join(n.rsplit(".", 2)[-2] + "." + n.rsplit(".", 1)[-1] for n in names)
        return f"{len(names)} small helper functions have never been run by any test: {short}"
    if c["id"] == "B3":
        return (
            "every known defect carries a severity"
            if c["passes"]
            else f"some open defects have no severity yet ({c['measured']})"
        )
    if c["id"] == "B5":
        return "every registered capability graded; none open, none unproven"
    return str(c["measured"])


def _q(text: str, left: bool = False) -> str:
    """A "?" marker whose explanation shows on hover, focus or tap."""
    cls = "rd-q rd-q--left" if left else "rd-q"
    return (
        f'<button type="button" class="{cls}" aria-label="What this means">?'
        f'<span class="rd-q__pop" role="tooltip">{html.escape(text)}</span></button>'
    )


def _cell(
    num: int,
    den: int,
    green_at: float = 1.0,
    amber_at: float = 0.5,
    na: str = "n/a",
    gap: str = "",
    na_tip: str = "",
) -> str:
    """One heat-map cell. ``gap`` names the missing part, e.g. "{n} grades never re-checked"."""
    if den == 0:
        return f'<td class="rd-h-n" title="{html.escape(na_tip)}">{na}</td>'
    share = num / den
    cls = "rd-h-g" if share >= green_at else ("rd-h-a" if share >= amber_at else "rd-h-r")
    tip = "All done." if num == den else gap.format(n=den - num)
    return f'<td class="{cls}" title="{html.escape(tip)}">{num:,} / {den:,}</td>'


def _heatmap(led: dict, unaudited: set, c1: dict, c2: dict, S) -> str:
    """One row per area, one column per condition, coloured by how far it is done."""
    from vfairness._registry import CAPABILITY_REGISTRY

    units = led["units"]
    area_of_cap = {}
    for e in CAPABILITY_REGISTRY.values():
        if e["pipeline_stage"] != "evaluation":
            continue
        name, mod = e["name"], "vfairness." + e["module_path"]
        hits = [q for q in units if q.endswith("." + name)]
        best = [q for q in hits if q.startswith(mod)] or hits
        area_of_cap[name] = units[best[0]]["area"] if best else "Top level"
    ref = {r["name"]: r["agree"] for r in c1.get("rows", [])}
    verdicts = c2.get("verdicts", {})

    rows = []
    for area in sorted(
        {r["area"] for r in units.values()},
        # Ties broken by name: two areas of equal size otherwise fall back to set
        # order, which Python randomises per process, and the --check in
        # refresh-docs.sh failed on alternate runs (seen four times 2026-10-01).
        key=lambda a: (-sum(1 for r in units.values() if r["area"] == a), a),
    ):
        au = {q: r for q, r in units.items() if r["area"] == area}
        total = len(au)
        examined = sum(1 for r in au.values() if r["status"] == S.CHECKED)
        confirmed = sum(1 for q, r in au.items() if r["status"] == S.CHECKED and q not in unaudited)
        fixes = sum(1 for r in au.values() if r["status"] == S.FIX_PENDING)
        caps = [n for n, a in area_of_cap.items() if a == area]
        with_ref = [n for n in caps if n in ref]
        measuring = [n for n in caps if verdicts.get(n) not in (None, "NOT A MEASUREMENT")]
        honest = [n for n in measuring if verdicts.get(n) == "PASS"]
        defect_cell = (
            '<td class="rd-h-g" title="No known defect in this area.">0</td>'
            if fixes == 0
            else f'<td class="rd-h-r" title="{fixes} proven defect(s) not yet fixed here.">{fixes}</td>'
        )
        rows.append(
            f"<tr><td>{html.escape(area)}</td>"
            + _cell(
                examined,
                total,
                green_at=1.0,
                amber_at=0.95,
                gap="{n} code unit(s) here have never been run by any test.",
            )
            + _cell(
                confirmed,
                examined,
                green_at=1.0,
                amber_at=0.5,
                gap="{n} grade(s) here have not been re-checked by a second examiner yet. Not failed: not yet looked at.",
            )
            + defect_cell
            + _cell(
                sum(1 for n in with_ref if ref[n]),
                len(with_ref),
                na="no reference",
                gap="{n} capability(ies) here give a different number from the reference library.",
                na_tip="No established library computes these numbers, so there is nothing to compare with.",
            )
            + _cell(
                len(honest),
                len(measuring),
                na="no measuring capability",
                gap="{n} capability(ies) here can invent a number on broken data.",
                na_tip="Nothing in this area produces a fairness number, so this check does not apply.",
            )
            + "</tr>"
        )
    head = (
        "<thead><tr><th>Area</th>"
        + "".join(
            f"<th>{title}{_q(text, left=i >= 3)}</th>" for i, (title, text) in enumerate(HEAT_HELP)
        )
        + "</tr></thead>"
    )
    cols = '<colgroup><col class="rd-c-area">' + '<col class="rd-c">' * 5 + "</colgroup>"
    return f'<table class="rd-heat">{cols}{head}<tbody>{"".join(rows)}</tbody></table>'


