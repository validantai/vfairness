def stamp(write: bool) -> bool:
    text = PAGE.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{PAGE} has lost its readiness markers")
    head, _s, tail = text.partition(START)
    _old, _e, rest = tail.partition(END)
    new = head + render() + rest
    if write and new != text:
        PAGE.write_text(new, encoding="utf-8")
    return new == text


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    same = stamp(write=not a.check)
    if a.check and not same:
        print(
            "STALE: the readiness block does not match its inputs; run scripts/render_readiness.py"
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
