#!/usr/bin/env python3
"""Put the three-state status where the capability is described, not in a footnote.

WHY THIS EXISTS. The status of every capability was measured and then published
in one place a reader never visits: a JSON file. The page where somebody decides
whether to call `detect_representation_bias` said nothing about whether anybody
has ever checked it. A measurement nobody can see at the point of decision is not
transparency, and this repository has already shipped the same shape of defect one
layer down: a verdict computed correctly and dropped at the boundary.

WHAT IT STAMPS, all from docs/capability-status.json, all idempotent:

  1. the published API reference page: a badge beside every documented symbol,
  2. docs/API_REFERENCE.md: the same badge as a markdown line under its heading,
  3. docs/site/status/index.html: the whole grid, all 1,558 units, searchable,
  4. the CSS for the badge, appended once to the one stylesheet the site uses.

STATIC, not fetched at render time. The site already binds numbers client-side and
that is fine for a KPI tile; it is not fine here. A badge that disappears when a
fetch fails leaves the page reading exactly as it did before any of this existed,
and a reader cannot tell "no badge" from "not checked". Stamped into the HTML, the
badge is in view-source, it is in the published artifact, and a test can compare
it against the ledger.

AMBIGUITY, resolved the safe way. One documented name can cover several code
units: `identify_proxy_variables` is documented twice and exists on two classes,
and a class badge has to answer for the methods a user reaches through it. When a
name covers several units the badge shows the WORST of them, in this order:

    FIX PENDING  >  NOT CHECKED  >  CHECKED

An open defect anywhere behind a name is the thing the reader most needs to know;
an unexamined unit behind a name is not something a badge may round up to checked.

Usage:
    python scripts/stamp_status_badges.py
    python scripts/stamp_status_badges.py --check     # exit 1 if any page is stale
"""

from __future__ import annotations

import argparse
import collections
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEDGER = ROOT / "docs" / "capability-status.json"
SITE = ROOT / "docs" / "site"
API_PAGE = SITE / "api-reference" / "index.html"
API_MD = ROOT / "docs" / "API_REFERENCE.md"
GRID_PAGE = SITE / "status" / "index.html"
QUALITY_PAGE = SITE / "quality-and-hardening" / "index.html"
STYLES = SITE / "css" / "styles.css"

CHECKED, FIX_PENDING, NOT_CHECKED = "CHECKED", "FIX PENDING", "NOT CHECKED"
WORST_FIRST = [FIX_PENDING, NOT_CHECKED, CHECKED]
SLUG = {CHECKED: "checked", FIX_PENDING: "fix-pending", NOT_CHECKED: "not-checked"}
SHORT = {CHECKED: "Checked", FIX_PENDING: "Fix pending", NOT_CHECKED: "Not checked"}

BADGE_OPEN, BADGE_CLOSE = "<!--cap-status-->", "<!--/cap-status-->"
CSS_MARK = "/* cap-status badges: generated by scripts/stamp_status_badges.py */"


def load() -> dict:
    if not LEDGER.exists():
        raise SystemExit("docs/capability-status.json missing; run scripts/capability_status.py")
    return json.loads(LEDGER.read_text(encoding="utf-8"))


def index_by_name(units: dict) -> dict[str, list[str]]:
    """short name -> every unit it could mean, class methods folded into the class."""
    by_tail: dict[str, list[str]] = collections.defaultdict(list)
    for qual in units:
        by_tail[qual.split(".")[-1]].append(qual)
    out: dict[str, list[str]] = {}
    for name, quals in by_tail.items():
        covered = list(quals)
        for qual in quals:
            if units[qual]["kind"] == "class":
                # A user reaching `Thing().method()` is relying on the methods,
                # so the class badge answers for them too.
                covered += [q for q in units if q.startswith(qual + ".")]
        out[name] = sorted(set(covered))
    return out


def verdict(units: dict, quals: list[str]) -> tuple[str, str]:
    """(status, tooltip) for a documented name covering `quals`."""
    statuses = [units[q]["status"] for q in quals]
    status = next(s for s in WORST_FIRST if s in statuses)
    counts = collections.Counter(statuses)
    if len(quals) == 1:
        tip = units[quals[0]]["detail"]
    else:
        parts = [f"{counts[s]} {SHORT[s].lower()}" for s in WORST_FIRST if counts[s]]
        tip = f"{len(quals)} code units behind this name: " + ", ".join(parts)
    return status, tip


def badge(status: str, tip: str, *, small: bool = False) -> str:
    cls = f"cap-status cap-status--{SLUG[status]}" + (" cap-status--sm" if small else "")
    return (
        f'{BADGE_OPEN}<a class="{cls}" href="../status/" '
        f'title="{html.escape(tip, quote=True)}" '
        f'data-cap-status="{status}">{SHORT[status]}</a>{BADGE_CLOSE}'
    )


