# A TABLE ROW whose first cell names a callable. The API reference documents 100
# code units this way and only 86 under a heading, so badging headings alone left
# most of the described surface unlabelled: the badge has to be where the reader
# meets the capability, and for a method summary table that is the row.
_MD_TABLE_ROW = re.compile(r"^\|\s*[`@]?([A-Za-z_][A-Za-z0-9_.]*)\(?\)?`?\s*\|(.*)\|\s*$", re.M)
_ROW_OPEN, _ROW_CLOSE = "<!--cs-->", "<!--/cs-->"

_MD_HEADING = re.compile(r"^(#{2,4})\s+[`@]?([A-Za-z_][A-Za-z0-9_.]*)[`]?(?:\(\))?(\s+.*)?$", re.M)
_MD_MARK = "<!-- cap-status:"
_MD_END = "<!-- /cap-status -->"


def stamp_api_md(led: dict, *, write: bool) -> tuple[int, str]:
    units, by_name = led["units"], index_by_name(led["units"])
    # Strip the WHOLE previous block, delimiters and body. Stripping only the
    # opening comment left the status line behind, so a second run stacked a
    # second one under the same heading: the check then reported the file stale
    # immediately after stamping it, which is how the bug surfaced.
    text = re.sub(
        r"\n?" + re.escape(_MD_MARK) + r".*?" + re.escape(_MD_END) + r"\n",
        # Empty, not "\n". The heading's own newline is still in the untouched
        # remainder, so putting one back accumulated a blank line per run and the
        # file was never byte-identical twice. Idempotence is the whole contract
        # here: a stamper that changes the file every time it is asked to check it
        # makes its own drift guard meaningless.
        "",
        API_MD.read_text(encoding="utf-8"),
        flags=re.S,
    )
    out, stamped, last = [], 0, 0
    for m in _MD_HEADING.finditer(text):
        quals = by_name.get(m.group(2).split(".")[-1])
        if not quals:
            continue
        status, tip = verdict(units, quals)
        out.append(text[last : m.end()])
        scope = (
            " **Preview:** documented and usable, and not yet fully covered and "
            "checked by the beta verification programme."
            if all(units[q].get("scope") == "preview" for q in quals)
            else ""
        )
        out.append(
            f"\n{_MD_MARK} {m.group(2)} -->\n"
            f"**Beta status: {SHORT[status]}.** {tip}{scope}\n{_MD_END}\n"
        )
        last = m.end()
        stamped += 1
    out.append(text[last:])
    new = _stamp_table_rows("".join(out), units, by_name)
    if write:
        API_MD.write_text(new, encoding="utf-8")
    return stamped, new


def _stamp_table_rows(text: str, units: dict, by_name: dict) -> str:
    """Badge every table row whose first cell names a code unit. Idempotent.

    Strips the whole previous marker INCLUDING the space before it, so the row is
    byte-identical after a second run: the heading stamper shipped with exactly
    that bug and its own drift check caught it.
    """
    text = re.sub(r" ?" + re.escape(_ROW_OPEN) + r".*?" + re.escape(_ROW_CLOSE), "", text)

    def repl(m: re.Match) -> str:
        name = m.group(1).split(".")[-1]
        quals = by_name.get(name)
        if not quals:
            return m.group(0)
        status, _tip = verdict(units, quals)
        row = m.group(0).rstrip()
        assert row.endswith("|")
        return f"{row[:-1].rstrip()} {_ROW_OPEN}**[{SHORT[status]}]**{_ROW_CLOSE} |"

    return _MD_TABLE_ROW.sub(repl, text)


