def _independent_check() -> tuple[set, int | None, int | None]:
    """(units nobody has independently checked, overturned ever, audited ever).

    Read from the register at render time, never written into this page by hand,
    so the number a reader meets here cannot drift from the one the gate measures.
    If the register cannot be read, the overturn figures come back None and the
    page says it could not state them rather than quoting a remembered one.
    """
    import sys

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    try:
        import library_kpis as _K

        graded = _K.graded_items()
        g = _K.grading()
    except Exception:
        return set(), None, None
    unaudited = {q for q, rec in graded.items() if not rec.get("audited")}
    return unaudited, g.get("audit_overturned_ever"), g.get("audited_ever")


