def stamp_css(*, write: bool) -> bool:
    text = STYLES.read_text(encoding="utf-8")
    if CSS_MARK in text:
        head, _sep, _tail = text.partition(CSS_MARK)
        new = head.rstrip() + "\n" + CSS.strip() + "\n"
    else:
        new = text.rstrip() + "\n\n" + CSS.strip() + "\n"
    if new != text and write:
        STYLES.write_text(new, encoding="utf-8")
    return new != text


_SITE_START, _SITE_END = "<!-- STATUS:site:start -->", "<!-- STATUS:site:end -->"


def _pct(n: int, d: int) -> str:
    return f"{100.0 * n / d:.1f}%" if d else "n/a"


def _site_summary(led: dict) -> str:
    """The three-state table for the published quality page.

    Rendered, not typed. Every hardcoded figure on this site has rotted at least
    once: a chunk count stale for months, a test count stale by 3,700, and a tile
    row adding two different countings of the same surface.
    """
    units = led["units"]
    total = len(units)
    counts = collections.Counter(r["status"] for r in units.values())
    # READ THE BOUNDARY, NEVER RESTATE IT. This was a literal tuple of three area
    # names, a second copy of a definition that lives in capability_status.py. When
    # the core was widened the definition moved and this copy did not, so the page
    # carried a section saying core is 1,382 units directly above a table saying it
    # is 390. One boundary, one place, read from the ledger that publishes it.
    core_areas = set(led.get("core_areas") or led.get("tier1_areas") or [])
    core = collections.Counter(r["status"] for r in units.values() if r["area"] in core_areas)
    core_total = sum(core.values())
    _named = sorted(core_areas)
    # Names as the ledger spells them: lowercasing turns "CI/CD gates" into
    # "ci/cd gates" and "Explainability (XAI)" into "(xai)".
    core_named = (
        ", ".join(_named[:-1]) + " and " + _named[-1]
        if len(_named) > 1
        else (_named[0] if _named else "not defined")
    )
    # EVERY CELL CARRIES A kpi- CLASS. This table was generated, so its figures were
    # never typed, but generated is only half of it: the page is served for as long
    # as it stands and this block was right at BUILD time alone, while the board one
    # screen above it refilled from library-stats.json on every load. Two tables of
    # the same ledger, one live and one frozen, is the drift this page exists about.
    # The literals here are the no-JavaScript fallback and stay correct because this
    # function writes them; tests/test_kpi_spans_are_live.py refuses a class that
    # renders two different values, so they cannot part company with the board's.
    rows = []
    for state, cls, share_cls in (
        (CHECKED, "kpi-ledger-checked", "kpi-share-checked"),
        (FIX_PENDING, "kpi-ledger-fix-pending", "kpi-share-fix"),
        (NOT_CHECKED, "kpi-ledger-not-checked", "kpi-share-unchecked"),
    ):
        core_cls = "kpi-core-" + {"CHECKED": "checked", "FIX PENDING": "fix"}.get(
            state, "unchecked"
        )
        share = _pct(counts[state], total)
        rows.append(
            f'<tr><td><span class="cap-status cap-status--{SLUG[state]} cap-status--sm">'
            f"{SHORT[state]}</span></td>"
            f'<td style="text-align:right"><span class="{cls}">{counts[state]:,}</span></td>'
            f'<td style="text-align:right"><span class="{share_cls}">'
            f"{share.rstrip('%')}</span>{'%' if share.endswith('%') else ''}</td>"
            f'<td style="text-align:right"><span class="{core_cls}">{core[state]:,}</span></td>'
            "</tr>"
        )
    dates = ", ".join(led.get("evidence_dates") or [])

    # THE SCOPE TABLE AND THE COLUMN THAT QUALIFIES IT, on the page Daniel reads.
    # Added 2026-10-01 after this exact table went onto the status page and into
    # CAPABILITY_STATUS.md while THIS page, the one he linked and reads, still had
    # neither. He reads HTML, not markdown, so a figure that is only in a .md file
    # has not been published to him. "Checked" means one examiner ran a unit and
    # recorded a result; the last column says how many of those results nobody has
    # yet tried to refute, and the sentence under it says how often that has failed.
    unaudited, overturned, audited_ever = _independent_check()
    scope = collections.defaultdict(collections.Counter)
    scope_unaudited = collections.Counter()
    for q, r in units.items():
        sc = "core" if r["area"] in core_areas else "preview"
        scope[sc][r["status"]] += 1
        if q in unaudited:
            scope_unaudited[sc] += 1
    scope_rows = []
    for sc, label in (
        ("core", "Core: what the beta promises"),
        ("preview", "Preview: documented, not certified"),
    ):
        c = scope[sc]
        scope_rows.append(
            f"<tr><td>{label}</td>"
            f'<td style="text-align:right">{sum(c.values()):,}</td>'
            f'<td style="text-align:right">{c[CHECKED]:,}</td>'
            f'<td style="text-align:right">{c[FIX_PENDING]:,}</td>'
            f'<td style="text-align:right">{c[NOT_CHECKED]:,}</td>'
            f'<td style="text-align:right"><strong>{scope_unaudited[sc]:,}</strong></td></tr>'
        )
    tot = scope["core"] + scope["preview"]
    scope_rows.append(
        f"<tr><td><strong>Total</strong></td>"
        f'<td style="text-align:right"><strong>{sum(tot.values()):,}</strong></td>'
        f'<td style="text-align:right"><strong>{tot[CHECKED]:,}</strong></td>'
        f'<td style="text-align:right"><strong>{tot[FIX_PENDING]:,}</strong></td>'
        f'<td style="text-align:right"><strong>{tot[NOT_CHECKED]:,}</strong></td>'
        f'<td style="text-align:right"><strong>{sum(scope_unaudited.values()):,}</strong></td></tr>'
    )
    if overturned and audited_ever:
        overturn_sentence = (
            f"<strong>Not independently checked</strong> counts grades one examiner "
            f"reached and nobody has yet tried to refute. Of the grades that HAVE been "
            f"through that second examination, <strong>{overturned:,} of "
            f"{audited_ever:,} ({100 * overturned / audited_ever:.0f}%) were "
            f"overturned</strong>, so a Checked unit in that column is a claim with "
            f"evidence behind it, not a settled result."
        )
    else:
        overturn_sentence = (
            "The overturn rate of independently checked grades could not be read here, "
            "so how far to trust an unchecked grade is NOT stated on this page."
        )
    scope_table = (
        '                    <h3 id="by-scope">Where the library stands, by scope</h3>\n'
        '                    <div class="table-container">\n'
        '                    <table class="qa-table">\n'
        "                      <thead><tr><th>Scope</th>"
        '<th style="text-align:right">Units</th>'
        '<th style="text-align:right">Checked</th>'
        '<th style="text-align:right">Fix pending</th>'
        '<th style="text-align:right">Not checked</th>'
        '<th style="text-align:right">Not independently checked</th></tr></thead>\n'
        "                      <tbody>\n"
        + "\n".join("                      " + r for r in scope_rows)
        + "\n                      </tbody>\n                    </table>\n"
        "                    </div>\n"
        f'                    <p class="qa-note">{overturn_sentence}</p>\n'
    )
    return f"""{_SITE_START}
{scope_table}                    <div class="table-container">
                    <table class="qa-table">
                      <thead><tr><th>State</th><th style="text-align:right">All code units</th>
                      <th style="text-align:right">Share</th>
                      <th style="text-align:right">Core</th></tr></thead>
                      <tbody>
{chr(10).join("                      " + r for r in rows)}
                      <tr><td><strong>Total</strong></td>
                      <td style="text-align:right"><strong class="kpi-ledger-total">{total:,}</strong></td>
                      <td style="text-align:right">100%</td>
                      <td style="text-align:right"><strong class="kpi-core-total">{core_total:,}</strong></td></tr>
                      </tbody>
                    </table>
                    </div>
                    <p class="qa-note">Assembled by <code>scripts/capability_status.py</code> from
                    evidence dated {dates}. <strong>Core</strong> is what the beta promises: every
                    area this project publishes a guide or a product page for, plus the top-level
                    namespace. That is {core_named}. The rest is
                    <a href="#what-the-beta-covers">preview</a>: documented and usable, and not
                    covered by the beta bar.</p>
{_SITE_END}"""


def stamp_quality_page(led: dict, *, write: bool) -> str:
    text = QUALITY_PAGE.read_text(encoding="utf-8")
    if _SITE_START not in text or _SITE_END not in text:
        raise SystemExit(f"{QUALITY_PAGE} has lost its status markers")
    head, _s, tail = text.partition(_SITE_START)
    _old, _e, rest = tail.partition(_SITE_END)
    new = head + _site_summary(led) + rest
    if write and new != text:
        QUALITY_PAGE.write_text(new, encoding="utf-8")
    return new


